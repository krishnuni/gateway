import { test, expect } from '@playwright/test'

test('Solar System, navigation, verified manifold lab and reproduction',async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('./')
  await expect(page.getByRole('heading',{name:'Our Solar System'})).toBeVisible()
  await expect(page.locator('main')).toHaveAttribute('data-complete','true',{timeout:30000})
  await page.screenshot({path:'docs/screenshots/solar-system.png'})
  const originalView=await page.locator('canvas').evaluate((c:HTMLCanvasElement)=>c.toDataURL())
  await page.getByRole('button',{name:'Navigate',exact:true}).click()
  await page.getByRole('button',{name:'Zoom in +',exact:true}).click()
  await page.getByRole('button',{name:'Rotate left',exact:true}).click()
  await page.waitForTimeout(200)
  expect(await page.locator('canvas').evaluate((c:HTMLCanvasElement)=>c.toDataURL())).not.toBe(originalView)
  await page.getByRole('button',{name:'Navigate',exact:true}).click()
  await page.getByRole('button',{name:'Explore Jupiter’s gateway'}).click()
  await expect(page.locator('main')).toHaveAttribute('data-complete','true',{timeout:30000})
  await expect(page.getByRole('heading',{name:'Through L₁'})).toBeVisible()
  await page.waitForTimeout(1800)
  await page.screenshot({path:'docs/screenshots/manifolds.png'})
  await page.getByRole('button',{name:'Inspect the mathematics'}).click()
  await expect(page.getByText('Computation complete',{exact:true})).toBeVisible()
  await expect(page.getByText('Closure residual',{exact:true})).toBeVisible()
  await page.screenshot({path:'docs/screenshots/diagnostics.png'})
  await page.getByRole('button',{name:'Close panel'}).click()
  await page.getByRole('button',{name:'Play',exact:true}).click()
  await expect(page.getByRole('button',{name:'Pause',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Pause',exact:true}).click()
  await page.getByRole('button',{name:'Views',exact:true}).click()
  await page.getByRole('menuitemradio',{name:'Poincaré section'}).click()
  await expect(page.getByRole('region',{name:'Poincaré section'})).toBeVisible()
  await page.screenshot({path:'docs/screenshots/section.png'})
  await page.getByRole('button',{name:'Experiment',exact:true}).click()
  await page.getByLabel('Orbit family',{exact:true}).selectOption('2')
  await expect(page.getByText('Previous geometry is shown until this experiment is recomputed.')).toBeVisible()
  await page.getByRole('button',{name:'Compute',exact:true}).click()
  await expect(page.getByRole('button',{name:'Compute',exact:true})).toBeEnabled({timeout:30000})
  await page.getByRole('button',{name:'Save or reproduce this experiment'}).click()
  await page.getByLabel('Experiment name').fill('Jovian L2 fixture')
  await page.getByRole('button',{name:'Save on this device'}).click()
  const downloadEvent=page.waitForEvent('download')
  await page.getByRole('button',{name:'Export recipe',exact:true}).click()
  const download=await downloadEvent
  expect(download.suggestedFilename()).toBe('gateway-sun-jupiter-l2.json')
  await expect(page.getByRole('button',{name:/^Jovian L2 fixture/})).toBeVisible()
  expect(errors).toEqual([])
})

test('scenario sensitivity, invalid recipe handling and cancellation recovery',async({page})=>{
  await page.goto('./')
  await page.getByRole('button',{name:'Open notebook and methods'}).click()
  await page.getByRole('button',{name:'Open experiment notebook',exact:true}).click()
  await page.getByRole('button',{name:'A small change',exact:false}).click()
  await expect(page.locator('main')).toHaveAttribute('data-complete','true',{timeout:30000})
  await page.getByRole('button',{name:'Inspect the mathematics'}).click()
  await expect(page.getByRole('heading',{name:'How nearby paths separate'})).toBeVisible()
  await page.screenshot({path:'docs/screenshots/sensitivity.png'})
  await page.getByRole('button',{name:'Experiment',exact:true}).click()
  await page.getByRole('button',{name:'Save or reproduce this experiment'}).click()
  await page.getByLabel('Import experiment file').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{"schema":99}')})
  await expect(page.getByRole('status').filter({hasText:'Unsupported experiment schema'})).toBeVisible()
  await page.getByRole('button',{name:'The lunar neck',exact:false}).click()
  await expect(page.locator('main')).toHaveAttribute('data-complete','true',{timeout:30000})
  await page.getByRole('button',{name:'Experiment',exact:true}).click()
  await page.getByRole('spinbutton',{name:/^Horizon/}).fill('30')
  await page.getByText('Numerical settings',{exact:true}).click()
  await page.getByRole('combobox',{name:/^Orbit phases/}).selectOption('128')
  await page.getByRole('button',{name:'Compute',exact:true}).click()
  const cancel=page.getByRole('button',{name:'Cancel computation',exact:true})
  await cancel.click({force:true})
  await expect(page.getByRole('button',{name:'Compute',exact:true})).toBeEnabled()
  await page.getByRole('spinbutton',{name:/^Horizon/}).fill('1')
  await page.getByRole('combobox',{name:/^Orbit phases/}).selectOption('16')
  await page.getByRole('button',{name:'Compute',exact:true}).click()
  await expect(page.locator('main')).toHaveAttribute('data-complete','true',{timeout:30000})
  await expect(page.getByRole('alert')).toHaveCount(0)
})

test('phone controls and an imported experiment',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('./')
  await page.getByRole('button',{name:'Experiment',exact:true}).click()
  await page.getByLabel('Focus on a planet').selectOption('2')
  await page.getByRole('button',{name:'Explore this gateway',exact:true}).click()
  await expect(page.locator('main')).toHaveAttribute('data-complete','true',{timeout:30000})
  await page.getByRole('button',{name:'Close panel'}).click()
  await page.waitForTimeout(2000)
  await page.screenshot({path:'docs/screenshots/phone.png'})
  await page.getByRole('button',{name:'Experiment',exact:true}).click()
  await page.getByRole('button',{name:'Save or reproduce this experiment'}).click()
  const recipe={schema:1,model:'pcr3bp-v1',system:'earth-moon',point:1,offset:.003,horizon:4,phases:16,
    epsilon:1e-6,tolerance:1e-11,mode:'manifolds',count:32,seed:1729,x:.82,y:0,angle:1.57,spread:.5,
    projection:'phase',stable:true,unstable:true}
  await page.getByLabel('Import experiment file').setInputFiles({name:'experiment.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({recipe}))})
  await expect(page.getByRole('status').filter({hasText:'Recipe imported.'})).toBeVisible()
  await expect(page.locator('main')).toHaveAttribute('data-complete','true',{timeout:30000})
})
